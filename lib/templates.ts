/** WORKFLOW.md 내용이 바뀌면 올린다. 파일 첫 줄의 버전과 비교해 갱신 여부를 정한다 */
export const WORKFLOW_VERSION = 5;
export const WORKFLOW_MARKER = (v: number) => `<!-- pinproof-workflow v${v} -->`;

export const WORKFLOW_MD = `${WORKFLOW_MARKER(WORKFLOW_VERSION)}
# PinProof 처리 절차

이 폴더(\`.pinproof/\`)에는 사용자가 브라우저 화면에서 직접 담은 **항목**이 쌓입니다.

- 항목 1개 = md 파일 1개: \`items/013.md\`. 스크린샷은 \`items/assets/013.png\`에 있습니다.
- 항목은 사용자가 만든 **카테고리**(frontmatter \`category\`, 예: 데이터 정합성 · UI·UX 개선 · 버그)로 묶입니다. 카테고리 목록은 \`categories.json\`에 있습니다.
- frontmatter \`status\`가 \`대기\`면 처리할 항목, \`완료\`면 처리가 끝난 항목입니다. \`sent\`는 사용자가 프롬프트로 넘긴 시각입니다(처리 여부와는 무관).
- \`items/archive/\`는 처리가 끝나 보관된 항목입니다. 따로 지시가 없으면 보지 않습니다.
- \`.pinproof/\` 바로 아래의 \`012-제목.md\`는 카테고리 이전 방식의 **옛 기록**(기록 건 1개에 증거 여러 개, 스크린샷은 \`assets/012/\`)입니다. 맨 아래 "옛 기록" 절차로 처리합니다. \`archive/\`는 보관된 옛 기록입니다.

프로젝트별 추가 규칙이 \`.pinproof/WORKFLOW.local.md\`에 있으면 그 내용도 함께 따릅니다(이 파일과 충돌하면 local이 우선).

\`.pinproof/\`는 보통 저장소의 메인 워크트리에만 있습니다. 지금 작업 폴더(git 워크트리)에 \`.pinproof/\`가 없으면 \`git worktree list\` 첫 줄(메인 워크트리) 아래의 \`.pinproof/\`를 씁니다. 항목 읽기와 \`status\`·\`## 처리 기록\` 쓰기는 그 경로에서, 코드 수정은 지금 작업 폴더에서 합니다.

## 무엇을 처리하나
- **인자가 없을 때: 목록.** \`items/*.md\`(archive 제외) 중 \`status: 대기\`인 항목을 카테고리별로 아래 형식으로만 보여주고 멈춥니다. 옛 기록이 있으면 마지막 줄에 개수만 적습니다.

\`\`\`
데이터 정합성 · 대기 2
  #013 요소 /dashboard · 총합이 목록 합과 다름
  #014 네트워크 /api/vms · 조회 실패 (넘김)
버그 · 대기 1
  #016 텍스트 /vm/12 · 상태 문구가 영어로 나옴
옛 기록 2건 · 번호로 처리(예: /pinproof 12)
\`\`\`

- **카테고리 이름이 주어졌을 때**: 그 카테고리의 \`대기\` 항목을 번호 순서로 하나씩 "항목 처리"대로 처리합니다. 이름이 정확히 맞지 않으면 비슷한 카테고리를 보여주며 묻습니다.
- **번호가 주어졌을 때**(여러 개도 됨, 예: \`13 14\`): \`items/<번호 3자리>.md\`를 "항목 처리"대로 처리합니다. 없으면 옛 기록 \`<번호 3자리>-*.md\`를 찾습니다. \`items/archive/\`에만 있으면 이미 끝난 항목이니 다시 처리할지 먼저 묻습니다.
- **프롬프트로 파일 목록을 받았을 때**: 사이드 패널의 [프롬프트 복사]는 처리할 항목 파일을 하나하나 적어 보냅니다. **적힌 파일만** 처리하고 목록에 없는 항목은 건드리지 않습니다(이미 넘긴 항목을 사용자가 기억하지 않아도 되게 하는 장치입니다).

## 항목 처리
1. 항목 md를 끝까지 읽습니다. \`note\`(본문의 메모)가 요청 내용입니다. 사용자가 자유롭게 쓴 글이라 현상·기대·추정·제약이 섞여 있을 수 있습니다. 제약(예: "로컬 기준으로만")은 반드시 지킵니다.
   - 이미 \`## 처리 기록\`이 있으면 **재처리**입니다(보관함에서 되돌린 항목 등). 이전 기록을 먼저 읽고, frontmatter의 \`updated\`가 마지막 처리 일시보다 늦으면 그 사이 메모·증거가 바뀐 것이니 바뀐 부분을 중심으로 다시 확인합니다. 이전 결론을 그대로 반복하지 말고, 새로 확인한 것과 달라진 결론만 적습니다.
2. 연결된 스크린샷·이미지를 열어 사용자가 본 화면을 확인합니다. \`붙여넣기\` 항목은 사용자가 다른 곳(메신저, 메일, 로그 등)에서 가져온 자료입니다. 영역 항목의 "영역 안에 보이던 글자"로 어떤 화면이었는지 특정할 수 있습니다.
3. 코드 위치를 찾습니다.
   - frontmatter가 \`env: deployed\`면 배포 주소에서 담은 항목입니다. 배포 빌드는 소스맵·React 개발 정보가 없어 \`참조\`에 소스 위치가 없거나 컴포넌트 이름이 압축되어 있을 수 있으니, 화면 글자·selector·API 경로로 코드를 찾습니다. 배포된 버전이 지금 로컬 코드와 다를 수 있으니(배포 뒤 바뀐 코드 등) 먼저 차이를 확인하고, 로컬에서 재현을 확인하지 못했으면 그 사실을 처리 기록에 적습니다.
   - \`참조\`에 소스 위치가 있으면 그 파일부터 봅니다. "근처"라고 표시된 줄 번호는 변환된 코드 기준이라 몇 줄 어긋날 수 있습니다.
   - 소스 위치가 없으면 컴포넌트 이름, 화면 텍스트, selector의 \`data-testid\`·\`id\`·\`aria-label\`로 코드를 검색합니다.
4. 값을 대조합니다. 값은 화면에 보인 원문 그대로 기록되어 있으며 익스텐션이 계산하지 않았습니다. 합계·개수·일치 여부는 직접 계산하고, 각 값을 만드는 API와 집계 로직을 끝까지 추적합니다. 메모가 다른 항목을 가리키면(예: "#013과 합이 다름") 그 항목 파일도 읽어 함께 대조합니다. 컨테이너 항목의 "화면에 보이는 행"은 가상 스크롤 때문에 전체가 아닐 수 있으니 데이터 출처(API, 쿼리)로 확인합니다.
5. 네트워크 항목이면 응답 내용과 화면 표시를 대조합니다. 응답은 앞부분만 기록되어 있습니다.
6. 판단 기준을 정합니다. 메모의 \`기대:\`가 기준입니다. 기대가 없는데 "요구사항이 맞나" 같은 판단이 필요하면 README·설계 문서에서 기준을 찾고, 문서끼리 또는 문서와 코드가 어긋나면 어느 쪽인지 단정하지 말고 어긋난 지점을 보여주며 사용자에게 묻습니다.
7. 원인을 먼저 설명하고 수정합니다.
   - 메모가 확인·질문만 요청하면(예: "맞는지 확인", "왜 이래?") 코드를 고치지 말고 확인 결과만 보고합니다.
   - 원인이 불확실하거나 수정 범위가 크면 수정 전에 사용자에게 물어봅니다.
8. 그 md 파일 맨 끝에 아래 형식으로 덧붙입니다.
   - 처음 처리: \`## 처리 기록\` 섹션을 만들고 그 아래에 \`### <일시>\` 항목을 씁니다.
   - 재처리: 기존 \`## 처리 기록\` 섹션 맨 아래에 \`### <일시> (재처리)\` 항목만 추가합니다. 섹션 제목을 새로 만들지 않습니다.

\`\`\`
## 처리 기록

### 2026-10-20 15:20
- 원인: …
- 수정한 파일: …
- 화면에서 확인할 방법: …
\`\`\`

9. **완료 표시**: 처리가 끝났으면 frontmatter의 \`status: 대기\`를 \`status: 완료\`로 바꿉니다. 끝났다는 것은 수정했거나(확인 요청이면 결과를 보고했고) 사용자에게 물을 것이 남지 않은 상태입니다. 사용자의 답을 기다리거나 재현하지 못했으면 \`대기\`로 두고, 처리 기록에 남은 일을 적습니다.
10. \`status\` 한 줄과 \`## 처리 기록\` 말고는 \`## 처리 기록\` 위쪽 내용을 고치지 않습니다(익스텐션이 다시 쓰는 영역입니다). 파일을 옮기지도 않습니다. 사이드 패널이 \`완료\` 항목을 \`items/archive/\`로 옮기고, 사용자가 화면에서 확인한 뒤 필요하면 되돌립니다(되돌리면 \`대기\`가 됩니다).
11. 여러 항목을 받았으면 항목마다 1~10을 마치고 다음 항목으로 갑니다. 모두 끝나면 항목마다 한 줄씩 결과를 요약합니다(예: \`#013 완료 · 합계에서 삭제된 VM 제외 누락\` / \`#014 대기 · 기대 동작 확인 필요\`).

## 옛 기록 (\`012-제목.md\`)
기록 건 1개에 증거(A·B·C)가 여러 개 있고 \`status\`가 없습니다. "항목 처리" 1~8을 기록 건 전체에 대해 하되 아래만 다릅니다.
- 증거들을 서로 대조합니다.
- frontmatter \`type\`이 \`확인 요청\`이면 코드를 고치지 말고 확인 결과만 보고합니다. \`버그\`·\`수정 요청\`이면 수정합니다.
- 완료 표시(\`status\`)는 쓰지 않습니다. 파일을 \`archive/\`로 옮기지 않습니다. 보관은 사용자가 사이드 패널에서 직접 합니다.
`;

/** WORKFLOW.md 첫 줄의 버전. 표시가 없으면 버전 표시 이전(v1)으로 본다 */
export function workflowVersionOf(text: string): number {
  const m = text.match(/^<!-- pinproof-workflow v(\d+) -->/);
  return m ? Number(m[1]) : 1;
}

/** .git/info/exclude 에 붙이는 블록. 내 컴퓨터에만 적용되고 모든 워크트리가 함께 쓴다(팀 .gitignore 는 건드리지 않음) */
export const EXCLUDE_BLOCK = `# PinProof
.pinproof/
`;

const EXCLUDE_LINES = ['.pinproof', '.pinproof/', '/.pinproof', '/.pinproof/'];

/** exclude 에 .pinproof 줄이 이미 있으면 null, 없으면 블록을 붙인 전체 내용 */
export function appendExclude(existing: string | null): string | null {
  if (existing?.split('\n').some((l) => EXCLUDE_LINES.includes(l.trim()))) return null;
  if (!existing) return EXCLUDE_BLOCK;
  const sep = existing.endsWith('\n') ? '\n' : '\n\n';
  return `${existing}${sep}${EXCLUDE_BLOCK}`;
}
